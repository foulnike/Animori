const PLAIN = 'С возвращением'

/** Ключ круга в хранилище: перезапуск приложения не должен начинать круг заново. */

// Колода, а не случайная фраза на каждый показ: случайная из реестра повторяется подряд, колода не даёт
// увидеть одну надпись дважды, пока не показан весь реестр целиком.
/** Номер надписи запуска: взят на старте, чтобы показ не ждал хранилища. null — ещё не взят. */
let launch: number | null = null

/** Идёт заготовка надписи: повторный зов ждёт тот же ход. */
let starting: Promise<void> | null = null

/** Тасовка Фишера — Йетса: любая перестановка реестра равновероятна. */
function shuffled(): number[] {
  const order = SPLASHES.map((_, at) => at)

  for (let i = order.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    const keep = order[i] ?? 0
    order[i] = order[j] ?? 0
    order[j] = keep
  }

  return order
}

/**
 * Колода нового круга. Первым номером не может стоять тот, которым кончился прошлый круг: иначе одна надпись
 * встала бы два показа подряд. Реестр из одной фразы — единственный случай, когда стык не развести. */
function dealt(past: number): number[] {
  const order = shuffled()
  // Первый номер, отличный от прошлого: он и встаёт на первое место вместо него.
  const other = order.findIndex((at) => at !== past)

  if (other > 0) {
    order[0] = order[other] ?? past
    order[other] = past
  }

  return order
}

/** Годен ли номер: реестр от выпуска к выпуску меняется, и старый круг может указывать мимо. */
function isAt(value: unknown): value is number {
  return (
    typeof value === 'number' && Number.isInteger(value) && value >= 0 && value < SPLASHES.length
  )
}

/**
 * Разбор записи хранилища. Числа вне реестра отбрасываются, а повтор в колоде отменяет запись целиком:
 * повтор означал бы две одинаковые надписи за круг.
 */
function parseRound(raw: unknown): Round | null {
  if (typeof raw !== 'object' || raw === null) return null

  const box = raw as Record<string, unknown>
  const stored = Array.isArray(box.rest) ? box.rest : []
  const order = stored.filter(isAt)

  if (new Set(order).size !== order.length) return null

  return { rest: order, last: isAt(box.last) ? box.last : -1 }
}

/** Читает круг. Пустое и битое читается как «круга не было»: он тасуется заново. */
async function readRound(): Promise<Round> {
  try {
    const stored = parseRound(await Bridge.storage.get<unknown>(STORE_KEY, null))
    if (stored !== null) return stored
  } catch (e) {
    Logger('WARN', 'Плашка: круг надписей не прочитался', e)
  }

  return { rest: [], last: -1 }
}

/** Пишет круг. Отказ не мешает показу, но и молчать нельзя: со сбитым кругом вернутся повторы. */
async function writeRound(round: Round): Promise<void> {
  try {
    await Bridge.storage.set(STORE_KEY, round)
  } catch (e) {
    Logger('WARN', 'Плашка: круг надписей не записался', e)
  }
}

/**
 * Ход круга: надпись берётся из колоды, и ход уходит в хранилище СРАЗУ, до показа. Запись после показа означала бы, что спам перезапуска показывает одну и ту же надпись: круг не сдвинулся.
 */
async function reserve(): Promise<void> {
  const round = await readRound()

  // Круг дошёл до конца — приходит новая тасовка; стык кругов держит dealt().
  if (round.rest.length === 0) round.rest = dealt(round.last)

  const at = round.rest[0] ?? -1
  round.rest = round.rest.slice(1)
  round.last = at
  launch = at

  await writeRound(round)
}

/** Заготовка надписи: зовётся из старта приложения до первой отрисовки. */
export function initSplash(): Promise<void> {
  starting ??= reserve()
  return starting
}

/**
 * Фраза плашки на этот запуск. Заготовлена initSplash(), сколько бы раз её ни спросили: на плашке строка стоит с первой отрисовки, а не появляется, когда ответит хранилище.
 */
export function splashLine(): string {
  return launch === null ? PLAIN : (SPLASHES[launch] ?? PLAIN)
}

const STORE_KEY = 'am_splash_round'

/** Круг, как он лежит в хранилище: номера ещё не показанных надписей и номер последней взятой. */
interface Round {
  rest: number[]
  last: number
}
